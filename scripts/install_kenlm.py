"""Install the KenLM Python module on Python 3.13+ (and anything else the stock wheel breaks on).

The kenlm sdist ships a C++ file generated by Cython 0.29, which doesn't compile on Python 3.13.
This downloads the sdist, regenerates that file from the bundled kenlm.pyx with a current Cython,
then builds and installs it. Needs the C++ build tools on Windows (already installed).

    python scripts/install_kenlm.py
"""
import glob, os, subprocess, sys, tarfile, tempfile

def run(*cmd, cwd=None):
    print("  $", " ".join(cmd)); subprocess.check_call(list(cmd), cwd=cwd)

def main():
    py = sys.executable
    try:
        import kenlm; print("kenlm already installed"); return
    except ImportError:
        pass
    with tempfile.TemporaryDirectory(prefix="kenlm_build_") as tmp:
        run(py, "-m", "pip", "install", "-q", "--upgrade", "cython>=3.1", "setuptools", "wheel", "cmake")
        run(py, "-m", "pip", "download", "-q", "--no-deps", "--no-binary", ":all:", "--no-build-isolation",
            "kenlm==0.3.0", "-d", tmp)
        tgz = glob.glob(os.path.join(tmp, "kenlm-*.tar.gz"))[0]
        with tarfile.open(tgz) as t:
            t.extractall(tmp)
        src = glob.glob(os.path.join(tmp, "kenlm-*/"))[0]
        run(py, "-m", "cython", "--cplus", "-3", os.path.join("python", "kenlm.pyx"),
            "-o", os.path.join("python", "kenlm.cpp"), cwd=src)
        run(py, "-m", "pip", "install", "-q", "--no-build-isolation", src)
    import importlib; importlib.invalidate_caches()
    subprocess.check_call([py, "-c", "import kenlm; print('kenlm ok', kenlm.__file__)"])

if __name__ == "__main__":
    main()
